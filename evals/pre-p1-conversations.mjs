export const preP1Scenarios = [];

for (const family of families) {
  for (const language of langs) {
    const rows = family.dialogs[language];
    if (!rows || rows.length !== 5)
      throw new Error(`pre-P1 family ${family.id}/${language} must have exactly 5 authored turns`);

    preP1Scenarios.push({
      id: `pre-p1-${family.id}-${language}`,
      suite: 'pre-p1-conversation-contract',
      priority: 'high',
      riskDomains: family.riskDomains ?? [],
      capabilities: family.capabilities,
      tags: [language, 'pre-p1', ...family.tags],
      matrixFamily: family.id,
      matrixLanguage: language,
      case: family.case ?? false,
      turns: rows.map((row) => ({
        ...row,
        language,
        target: {
          ...row.target,
          responseLanguage: row.target.responseLanguage ?? language,
        },
      })),
    });
  }
}

